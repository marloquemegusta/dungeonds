#!/usr/bin/env python3
"""Length in vblanks (60 per second) of each boss voice, from the sample count of its baked WAV.
Writes include/sfx_voice_len.h; run again whenever a voice in assets/sfx/baked/ changes."""
import os
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICES = [("ABANDERADO_INTRO", "abanderado_intro.wav"), ("ABANDERADO_DEFEAT", "abanderado_derrota.wav"),
          ("CAMPANERO_INTRO", "campanero_intro.wav"), ("CAMPANERO_DEFEAT", "campanero_derrota.wav")]

lines = ["/* Generated by tools/gen_voice_lengths.py - DO NOT EDIT */", "#ifndef SFX_VOICE_LEN_H", "#define SFX_VOICE_LEN_H", ""]
for name, fname in VOICES:
    with wave.open(os.path.join(ROOT, "assets", "sfx", "baked", fname), "rb") as w:
        frames = -(-w.getnframes() * 60 // w.getframerate())
    lines.append(f"#define SFX_VOICE_VBLANKS_{name} {frames}")
lines += ["", "#endif", ""]
with open(os.path.join(ROOT, "include", "sfx_voice_len.h"), "w", newline="\n") as f:
    f.write("\n".join(lines))
