#!/usr/bin/env python3
"""Bakes the ARPG HUD sprites (caliz, ampolla, cadena_xp, 4x viril) into C data.

Outputs:
  include/arpg_hud_gfx.h
  source/arpg_hud_gfx.c
"""
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
HUD = ROOT / "assets" / "sprites" / "hud"


def to_bgr555(r, g, b):
    r5 = min(31, (int(r) * 31 + 127) // 255)
    g5 = min(31, (int(g) * 31 + 127) // 255)
    b5 = min(31, (int(b) * 31 + 127) // 255)
    return 0x8000 | r5 | (g5 << 5) | (b5 << 10)


def img_to_words(path):
    im = Image.open(path).convert("RGBA")
    out = []
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = im.getpixel((x, y))
            out.append(0 if a < 128 else to_bgr555(r, g, b))
    return im.width, im.height, out


def bowl_bounds(path, y_min_frac, y_max_frac):
    im = Image.open(path).convert("RGBA")
    arr = np.array(im)
    alpha = arr[..., 3] > 128
    h, w = alpha.shape
    xl_arr = [-1] * h
    xr_arr = [-1] * h
    y_first, y_last = h, -1
    for y in range(int(h * y_min_frac), int(h * y_max_frac)):
        xs = np.where(alpha[y])[0]
        if len(xs) >= 2:
            xl, xr = int(xs[0]), int(xs[-1])
            if xr - xl > w * 0.25 and not alpha[y, xl:xr + 1].all():
                xl_arr[y] = xl
                xr_arr[y] = xr
                if y < y_first:
                    y_first = y
                y_last = y
    return y_first, y_last, xl_arr, xr_arr


def write_lf(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def main():
    sprites = [
        ("g_hud_caliz", "caliz.png"),
        ("g_hud_ampolla", "ampolla.png"),
        ("g_hud_cadena", "cadena_xp.png"),
        ("g_hud_viril_rayo", "viril_rayo.png"),
        ("g_hud_viril_glifo", "viril_glifo.png"),
        ("g_hud_viril_ejecucion", "viril_ejecucion.png"),
        ("g_hud_viril_levantar", "viril_levantar.png"),
    ]

    parsed = []
    for sym, fname in sprites:
        w, h, px = img_to_words(HUD / fname)
        parsed.append((sym, fname, w, h, px))

    cal_ymin, cal_ymax, cal_xl, cal_xr = bowl_bounds(HUD / "caliz.png", 0.20, 0.70)
    amp_ymin, amp_ymax, amp_xl, amp_xr = bowl_bounds(HUD / "ampolla.png", 0.24, 0.74)

    hdr = [
        "// GENERATED by tools/hud/generate_arpg_hud_c.py. Do not edit.",
        "#ifndef ARPG_HUD_GFX_H",
        "#define ARPG_HUD_GFX_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for sym, fname, w, h, _ in parsed:
        tag = sym.replace("g_hud_", "").upper()
        hdr.append(f"#define HUD_{tag}_W {w}")
        hdr.append(f"#define HUD_{tag}_H {h}")
        hdr.append(f"extern const uint16_t {sym}[{w * h}];")
    hdr += [
        "",
        f"#define HUD_CALIZ_BOWL_TOP {cal_ymin}",
        f"#define HUD_CALIZ_BOWL_BOT {cal_ymax}",
        "extern const int8_t g_hud_caliz_xl[HUD_CALIZ_H];",
        "extern const int8_t g_hud_caliz_xr[HUD_CALIZ_H];",
        "",
        f"#define HUD_AMPOLLA_BOWL_TOP {amp_ymin}",
        f"#define HUD_AMPOLLA_BOWL_BOT {amp_ymax}",
        "extern const int8_t g_hud_ampolla_xl[HUD_AMPOLLA_H];",
        "extern const int8_t g_hud_ampolla_xr[HUD_AMPOLLA_H];",
        "",
        "#endif",
        "",
    ]
    write_lf(ROOT / "include" / "arpg_hud_gfx.h", "\n".join(hdr))

    c = [
        "// GENERATED by tools/hud/generate_arpg_hud_c.py. Do not edit.",
        '#include "arpg_hud_gfx.h"',
        "",
    ]
    for sym, fname, w, h, px in parsed:
        c.append(f"// {fname} ({w}x{h})")
        c.append(f"const uint16_t {sym}[{w * h}] = {{")
        for y in range(h):
            c.append("    " + ", ".join(f"0x{v:04X}" for v in px[y * w:(y + 1) * w]) + ",")
        c.append("};")
        c.append("")

    for arr_name, arr in [
        ("g_hud_caliz_xl", cal_xl),
        ("g_hud_caliz_xr", cal_xr),
        ("g_hud_ampolla_xl", amp_xl),
        ("g_hud_ampolla_xr", amp_xr),
    ]:
        c.append(f"const int8_t {arr_name}[{len(arr)}] = {{ " + ", ".join(str(v) for v in arr) + " };")
    c.append("")
    write_lf(ROOT / "source" / "arpg_hud_gfx.c", "\n".join(c))
    print("Wrote arpg_hud_gfx.c/.h")


if __name__ == "__main__":
    main()
