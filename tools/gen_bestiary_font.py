#!/usr/bin/env python3
"""
tools/gen_bestiary_font.py - Generates 1-bit bitmap font for DungeonDS Bestiary.

Produces:
  include/bestiary_font.h
  source/bestiary_font.c
  walkthroughs/bestiario/assets/font_preview.png

Covers printable ASCII (0x20..0x7E) plus Spanish characters:
  á é í ó ú ü ñ Á É Í Ó Ú Ü Ñ ¡ ¿ « » — ·
"""

import os
import sys
import argparse
from PIL import Image, ImageFont

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
WT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, '..'))

DEFAULT_FONT = r'C:\Windows\Fonts\pala.ttf'
DEFAULT_SIZE = 11
DEFAULT_THRESH = 100
DEFAULT_MONO = True

SPANISH_CHARS = [
    '¡', '«', '·', '»', '¿',
    'Á', 'É', 'Í', 'Ñ', 'Ó', 'Ú', 'Ü',
    'á', 'é', 'í', 'ñ', 'ó', 'ú', 'ü',
    '—'
]

def collect_glyphs(font_path, font_size, threshold, mono=False):
    if mono:
        font = ImageFont.truetype(font_path, font_size, layout_engine=ImageFont.Layout.BASIC)
    else:
        font = ImageFont.truetype(font_path, font_size)
    ascii_chars = [chr(c) for c in range(0x20, 0x7F)]
    all_chars = ascii_chars + sorted(SPANISH_CHARS, key=lambda c: ord(c))

    glyphs = []
    bitmaps = bytearray()

    for ch in all_chars:
        cp = ord(ch)
        adv = int(round(font.getlength(ch, mode='1') if mono else font.getlength(ch)))
        if ch == ' ':
            glyphs.append({
                'char': ch,
                'codepoint': cp,
                'width': 0,
                'height': 0,
                'x_offset': 0,
                'y_offset': 0,
                'advance': adv,
                'bitmap_offset': 0,
                'rows': []
            })
            continue

        if mono:
            bbox = font.getbbox(ch, mode='1')
            mask = font.getmask(ch, mode='1')
        else:
            bbox = font.getbbox(ch)
            mask = font.getmask(ch, 'L')
        gw, gh = mask.size
        x0, y0, x1, y1 = bbox

        row_data = []
        glyph_bytes = bytearray()
        for r in range(gh):
            row_bits = [(1 if (mask.getpixel((c, r)) > 0 if mono else mask.getpixel((c, r)) >= threshold) else 0) for c in range(gw)]
            row_data.append(row_bits)
            bytes_per_row = (gw + 7) // 8
            rb = bytearray(bytes_per_row)
            for c in range(gw):
                if row_bits[c]:
                    rb[c >> 3] |= (1 << (7 - (c & 7)))
            glyph_bytes.extend(rb)

        bmp_off = len(bitmaps)
        bitmaps.extend(glyph_bytes)

        glyphs.append({
            'char': ch,
            'codepoint': cp,
            'width': gw,
            'height': gh,
            'x_offset': x0,
            'y_offset': y0,
            'advance': adv,
            'bitmap_offset': bmp_off,
            'rows': row_data
        })

    return font, glyphs, bitmaps

def generate_header(out_h_path):
    content = """/* Automatically generated by tools/gen_bestiary_font.py - DO NOT EDIT */
#ifndef BESTIARY_FONT_H
#define BESTIARY_FONT_H

#include <stdint.h>
#include <stddef.h>

#define BESTIARY_FONT_LINE_HEIGHT 13

typedef struct {
    uint32_t codepoint;       /* Unicode codepoint (e.g. 'A', 0x00E1) */
    uint8_t  width;           /* Width of the glyph bitmap in pixels */
    uint8_t  height;          /* Height of the glyph bitmap in pixels */
    int8_t   x_offset;        /* Left offset relative to pen position */
    int8_t   y_offset;        /* Top offset relative to line baseline/top */
    uint8_t  advance;         /* Horizontal pen advance in pixels */
    uint16_t bitmap_offset;   /* Byte offset into bitmap byte pool */
} BestiaryGlyph;

/* Line height of the font in pixels */
int bestiary_font_line_height(void);

/* Returns pointer to glyph metrics and bitmap, or NULL if not available */
const BestiaryGlyph *bestiary_font_get_glyph(uint32_t codepoint);

/* Measures width in pixels of a UTF-8 string (returns max width across lines if multi-line) */
int bestiary_font_measure_utf8(const char *utf8);

/* Draws a UTF-8 string to a 256-wide 16-bit framebuffer (BgType_Bmp16 / RGB15).
 * Clips cleanly to screen bounds (256x192). Handles '\\n' for newlines.
 */
void bestiary_font_draw_utf8(uint16_t *fb, int x, int y, const char *utf8, uint16_t color);

/* Draws wrapped UTF-8 text respecting word boundaries and '\\n'.
 * max_w: maximum width in pixels before wrapping.
 * line_step: vertical distance between lines (if <= 0, uses bestiary_font_line_height()).
 */
void bestiary_font_draw_wrapped(uint16_t *fb, int x, int y, int max_w, int line_step, const char *utf8, uint16_t color);

#endif /* BESTIARY_FONT_H */
"""
    os.makedirs(os.path.dirname(out_h_path), exist_ok=True)
    with open(out_h_path, 'w', encoding='utf-8') as f:
        f.write(content)

def generate_source(out_c_path, glyphs, bitmaps):
    ascii_glyphs = [g for g in glyphs if 0x20 <= g['codepoint'] <= 0x7E]
    spanish_glyphs = [g for g in glyphs if g['codepoint'] > 0x7E]
    spanish_glyphs.sort(key=lambda g: g['codepoint'])

    lines = []
    lines.append('/* Automatically generated by tools/gen_bestiary_font.py - DO NOT EDIT */\n')
    lines.append('#include "bestiary_font.h"\n')
    lines.append('#include <stdbool.h>\n\n')

    # Bitmaps array
    lines.append(f'static const uint8_t s_font_bitmaps[{len(bitmaps)}] __attribute__((aligned(4))) = {{\n')
    for i in range(0, len(bitmaps), 16):
        chunk = bitmaps[i:i+16]
        hex_vals = ', '.join(f'0x{b:02X}' for b in chunk)
        lines.append(f'    {hex_vals},\n')
    lines.append('};\n\n')

    def format_glyph(g):
        char_desc = g['char']
        if char_desc == '\\':
            char_desc = '\\\\'
        elif char_desc == '\'':
            char_desc = '\\\''
        return (f"    {{ 0x{g['codepoint']:04X}, {g['width']}, {g['height']}, "
                f"{g['x_offset']}, {g['y_offset']}, {g['advance']}, {g['bitmap_offset']} }}"
                f" /* '{char_desc}' */")

    # ASCII table
    lines.append(f'static const BestiaryGlyph s_ascii_glyphs[{len(ascii_glyphs)}] = {{\n')
    for g in ascii_glyphs:
        lines.append(format_glyph(g) + ',\n')
    lines.append('};\n\n')

    # Spanish table (sorted by codepoint)
    lines.append(f'static const BestiaryGlyph s_spanish_glyphs[{len(spanish_glyphs)}] = {{\n')
    for g in spanish_glyphs:
        lines.append(format_glyph(g) + ',\n')
    lines.append('};\n\n')

    # Functions implementation
    lines.append("""static uint32_t decode_utf8(const char **src) {
    const uint8_t *s = (const uint8_t *)*src;
    uint32_t cp = 0;
    if (!*s) return 0;
    if (*s < 0x80) {
        cp = *s++;
    } else if ((*s & 0xE0) == 0xC0) {
        cp = (uint32_t)(*s++ & 0x1F) << 6;
        if ((*s & 0xC0) == 0x80) cp |= (*s++ & 0x3F);
    } else if ((*s & 0xF0) == 0xE0) {
        cp = (uint32_t)(*s++ & 0x0F) << 12;
        if ((*s & 0xC0) == 0x80) {
            cp |= (uint32_t)(*s++ & 0x3F) << 6;
            if ((*s & 0xC0) == 0x80) cp |= (*s++ & 0x3F);
        }
    } else if ((*s & 0xF8) == 0xF0) {
        cp = (uint32_t)(*s++ & 0x07) << 18;
        if ((*s & 0xC0) == 0x80) {
            cp |= (uint32_t)(*s++ & 0x3F) << 12;
            if ((*s & 0xC0) == 0x80) {
                cp |= (uint32_t)(*s++ & 0x3F) << 6;
                if ((*s & 0xC0) == 0x80) cp |= (*s++ & 0x3F);
            }
        }
    } else {
        s++;
    }
    *src = (const char *)s;
    return cp;
}

int bestiary_font_line_height(void) {
    return BESTIARY_FONT_LINE_HEIGHT;
}

const BestiaryGlyph *bestiary_font_get_glyph(uint32_t codepoint) {
    if (codepoint >= 0x20 && codepoint <= 0x7E) {
        return &s_ascii_glyphs[codepoint - 0x20];
    }
    int low = 0;
    int high = (int)(sizeof(s_spanish_glyphs) / sizeof(s_spanish_glyphs[0])) - 1;
    while (low <= high) {
        int mid = (low + high) >> 1;
        uint32_t mid_cp = s_spanish_glyphs[mid].codepoint;
        if (mid_cp == codepoint) {
            return &s_spanish_glyphs[mid];
        }
        if (mid_cp < codepoint) {
            low = mid + 1;
        } else {
            high = mid - 1;
        }
    }
    return NULL;
}

static void draw_glyph(uint16_t *fb, int pen_x, int pen_y, const BestiaryGlyph *g, uint16_t color) {
    if (!fb || !g || g->width == 0 || g->height == 0) return;
    int bytes_per_row = (g->width + 7) >> 3;
    const uint8_t *bmp = &s_font_bitmaps[g->bitmap_offset];
    for (int r = 0; r < (int)g->height; r++) {
        int py = pen_y + g->y_offset + r;
        if (py < 0 || py >= 192) continue;
        const uint8_t *row_bytes = bmp + r * bytes_per_row;
        uint16_t *fb_row = fb + (py << 8);
        for (int c = 0; c < (int)g->width; c++) {
            if ((row_bytes[c >> 3] >> (7 - (c & 7))) & 1) {
                int px = pen_x + g->x_offset + c;
                if (px >= 0 && px < 256) {
                    fb_row[px] = color;
                }
            }
        }
    }
}

int bestiary_font_measure_utf8(const char *utf8) {
    if (!utf8) return 0;
    int max_w = 0;
    int cur_w = 0;
    const char *p = utf8;
    while (*p) {
        if (*p == '\\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
            p++;
            continue;
        }
        if (*p == '\\r') {
            p++;
            continue;
        }
        uint32_t cp = decode_utf8(&p);
        const BestiaryGlyph *g = bestiary_font_get_glyph(cp);
        if (!g) g = bestiary_font_get_glyph('?');
        if (g) cur_w += g->advance;
    }
    if (cur_w > max_w) max_w = cur_w;
    return max_w;
}

void bestiary_font_draw_utf8(uint16_t *fb, int x, int y, const char *utf8, uint16_t color) {
    if (!fb || !utf8) return;
    int pen_x = x;
    int pen_y = y;
    int lh = bestiary_font_line_height();
    const char *p = utf8;
    while (*p) {
        if (*p == '\\n') {
            pen_x = x;
            pen_y += lh;
            p++;
            continue;
        }
        if (*p == '\\r') {
            p++;
            continue;
        }
        uint32_t cp = decode_utf8(&p);
        const BestiaryGlyph *g = bestiary_font_get_glyph(cp);
        if (!g) g = bestiary_font_get_glyph('?');
        if (g) {
            draw_glyph(fb, pen_x, pen_y, g, color);
            pen_x += g->advance;
        }
    }
}

void bestiary_font_draw_wrapped(uint16_t *fb, int x, int y, int max_w, int line_step, const char *utf8, uint16_t color) {
    if (!fb || !utf8 || max_w <= 0) return;
    if (line_step <= 0) line_step = bestiary_font_line_height();
    int cur_x = x;
    int cur_y = y;
    const char *p = utf8;

    while (*p) {
        if (*p == '\\n') {
            cur_x = x;
            cur_y += line_step;
            p++;
            continue;
        }
        if (*p == '\\r') {
            p++;
            continue;
        }
        if (*p == ' ') {
            if (cur_x == x) {
                p++;
                continue;
            }
            const BestiaryGlyph *g_sp = bestiary_font_get_glyph(' ');
            int sp_w = g_sp ? (int)g_sp->advance : 3;
            cur_x += sp_w;
            p++;
            continue;
        }

        const char *w_start = p;
        const char *w_ptr = p;
        int word_w = 0;
        while (*w_ptr && *w_ptr != ' ' && *w_ptr != '\\n' && *w_ptr != '\\r') {
            uint32_t cp = decode_utf8(&w_ptr);
            const BestiaryGlyph *g = bestiary_font_get_glyph(cp);
            if (!g) g = bestiary_font_get_glyph('?');
            if (g) word_w += g->advance;
        }

        if (cur_x + word_w > x + max_w && cur_x > x) {
            cur_x = x;
            cur_y += line_step;
        }

        p = w_start;
        while (p < w_ptr) {
            uint32_t cp = decode_utf8(&p);
            const BestiaryGlyph *g = bestiary_font_get_glyph(cp);
            if (!g) g = bestiary_font_get_glyph('?');
            if (g) {
                draw_glyph(fb, cur_x, cur_y, g, color);
                cur_x += g->advance;
            }
        }
    }
}
""")

    os.makedirs(os.path.dirname(out_c_path), exist_ok=True)
    with open(out_c_path, 'w', encoding='utf-8') as f:
        f.writelines(lines)

def render_preview_image(glyphs, preview_path):
    glyph_map = {g['char']: g for g in glyphs}

    def draw_text(im, x, y, text, color):
        pen_x = x
        for ch in text:
            g = glyph_map.get(ch, glyph_map.get('?'))
            if not g: continue
            for r, row in enumerate(g['rows']):
                py = y + g['y_offset'] + r
                if 0 <= py < im.height:
                    for c, bit in enumerate(row):
                        if bit:
                            px = pen_x + g['x_offset'] + c
                            if 0 <= px < im.width:
                                im.putpixel((px, py), color)
            pen_x += g['advance']
        return pen_x

    def measure_word(w):
        return sum(glyph_map.get(c, glyph_map.get('?'))['advance'] for c in w)

    def draw_wrapped(im, x, y, max_w, line_step, text, color):
        cur_x = x
        cur_y = y
        paras = text.split('\n')
        for p_idx, para in enumerate(paras):
            if p_idx > 0:
                cur_x = x
                cur_y += line_step
            if not para:
                continue
            words = para.split(' ')
            for word in words:
                if not word: continue
                ww = measure_word(word)
                sp_w = glyph_map[' ']['advance']
                needed = ww if cur_x == x else (sp_w + ww)
                if cur_x + needed > x + max_w and cur_x > x:
                    cur_x = x
                    cur_y += line_step
                elif cur_x > x:
                    cur_x += sp_w
                draw_text(im, cur_x, cur_y, word, color)
                cur_x += ww

    im = Image.new('RGB', (256, 192), (0, 0, 0))

    # 1px border around screen simulating DS screen margin
    for x in range(2, 254):
        im.putpixel((x, 2), (55, 55, 55))
        im.putpixel((x, 189), (55, 55, 55))
    for y in range(2, 190):
        im.putpixel((2, y), (55, 55, 55))
        im.putpixel((253, y), (55, 55, 55))

    # Header title
    draw_text(im, 10, 8, 'EL EXVOTO', (245, 240, 225))
    draw_text(im, 88, 8, '(Masa)', (165, 155, 145))

    # Behavior
    draw_text(im, 10, 26, 'Comportamiento:', (185, 175, 155))
    draw_wrapped(im, 10, 39, 236, 13, 'Avanza en masa sin descanso; cae al primer impacto.', (215, 210, 200))

    # Lore
    draw_text(im, 10, 68, 'Historia:', (185, 175, 155))
    draw_wrapped(im, 10, 81, 236, 13,
                 'Fieles que rezaron hasta volverse figuras de cera. Siguen en procesión con las manos en rezo; la cera no resiste la luz.',
                 (195, 190, 180))

    # Quote
    draw_wrapped(im, 10, 122, 236, 13, '«Pidieron no estar solos. Les fue concedido.»', (235, 220, 185))

    # Character set proof
    draw_text(im, 10, 148, 'á é í ó ú ü ñ  Á É Í Ó Ú Ü Ñ  ¡¿ — ·', (145, 140, 130))

    # Navigation
    draw_text(im, 14, 172, '< Ant', (215, 210, 200))
    draw_text(im, 110, 172, 'Volver', (245, 240, 225))
    draw_text(im, 215, 172, 'Sig >', (215, 210, 200))

    os.makedirs(os.path.dirname(preview_path), exist_ok=True)
    im.save(preview_path)
    print(f'Preview saved: {preview_path}')

def main():
    parser = argparse.ArgumentParser(description='Generate 1-bit bitmap font for Bestiary')
    parser.add_argument('--font', default=DEFAULT_FONT, help='TTF font path')
    parser.add_argument('--size', type=int, default=DEFAULT_SIZE, help='Font point size')
    parser.add_argument('--threshold', type=int, default=DEFAULT_THRESH, help='Binarization threshold (0..255)')
    parser.add_argument('--mono', dest='mono', action='store_true', default=DEFAULT_MONO, help='Hinted 1-bit rasterization (default)')
    parser.add_argument('--no-mono', dest='mono', action='store_false', help='Antialiased + threshold')
    parser.add_argument('--out-h', default=os.path.join(WT_ROOT, 'include', 'bestiary_font.h'))
    parser.add_argument('--out-c', default=os.path.join(WT_ROOT, 'source', 'bestiary_font.c'))
    parser.add_argument('--out-preview', default=os.path.join(WT_ROOT, 'walkthroughs', 'bestiario', 'assets', 'font_preview.png'))
    parser.add_argument('--prefix', default='bestiary', help="Nombre de los símbolos (p. ej. 'inv' → inv_font_*, InvGlyph)")
    parser.add_argument('--line-height', type=int, default=0, help='Altura de línea (0 = la del bestiario, 13)')
    args = parser.parse_args()

    print(f'Loading font: {args.font} at size {args.size}...')
    font, glyphs, bitmaps = collect_glyphs(args.font, args.size, args.threshold, args.mono)
    print(f'Collected {len(glyphs)} glyphs, {len(bitmaps)} bytes of bitmap data.')

    print(f'Writing {args.out_h}...')
    generate_header(args.out_h)

    print(f'Writing {args.out_c}...')
    generate_source(args.out_c, glyphs, bitmaps)

    print(f'Rendering preview {args.out_preview}...')
    render_preview_image(glyphs, args.out_preview)

    if args.prefix != 'bestiary' or args.line_height:
        pre = args.prefix
        for path in (args.out_h, args.out_c):
            with open(path, encoding='utf-8', newline='') as f:
                t = f.read()
            t = t.replace('bestiary_font', pre + '_font').replace('BESTIARY_FONT', pre.upper() + '_FONT')
            t = t.replace('gen_' + pre + '_font.py', 'gen_bestiary_font.py')
            t = t.replace('BestiaryGlyph', pre.capitalize() + 'Glyph')
            if args.line_height:
                t = t.replace('LINE_HEIGHT 13', 'LINE_HEIGHT %d' % args.line_height)
            with open(path, 'w', encoding='utf-8', newline='') as f:
                f.write(t)
    print('Bestiary font generation complete.')

if __name__ == '__main__':
    main()
