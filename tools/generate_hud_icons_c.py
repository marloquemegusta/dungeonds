#!/usr/bin/env python3
"""Converts the HUD icon PNGs into C data for the ROM.

  assets/sprites/hud/heart_full.png, heart_empty.png  ->  source/hud_icons_gfx.c + include/hud_icons_gfx.h

Pixels are BGR555 with BIT(15) set when opaque; 0 means transparent (alpha < 128).
Both PNGs must have the same size.

To swap in the final Sacred Heart render: overwrite the two PNGs (same size, RGBA, transparent
background), then run from the repo root:
    python tools/generate_hud_icons_c.py
and rebuild. Nothing in the C code needs to change unless the size changes (it is read from the header).
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "sprites" / "hud"
ICONS = [("g_hud_heart_full", "heart_full.png"), ("g_hud_heart_empty", "heart_empty.png")]


def words(path):
    img = Image.open(path).convert("RGBA")
    out = []
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = img.getpixel((x, y))
            if a < 128:
                out.append(0)
            else:
                r5 = min(31, (r * 31 + 127) // 255)
                g5 = min(31, (g * 31 + 127) // 255)
                b5 = min(31, (b * 31 + 127) // 255)
                out.append(0x8000 | r5 | (g5 << 5) | (b5 << 10))
    return img.width, img.height, out


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:  # keep LF on Windows
        f.write(text)


def main():
    data = [(name, png) + words(SRC / png) for name, png in ICONS]
    w, h = data[0][2], data[0][3]
    assert all((d[2], d[3]) == (w, h) for d in data), "icons must share one size"

    c = ["// GENERATED by tools/generate_hud_icons_c.py from assets/sprites/hud/*.png. Do not edit.",
         '#include "hud_icons_gfx.h"', ""]
    for name, png, _, _, px in data:
        c.append(f"// {png}")
        c.append(f"const uint16_t {name}[HUD_ICON_W * HUD_ICON_H] = {{")
        for y in range(h):
            c.append("    " + ", ".join(f"0x{v:04X}" for v in px[y * w:(y + 1) * w]) + ",")
        c.append("};")
        c.append("")
    write(ROOT / "source" / "hud_icons_gfx.c", "\n".join(c))

    hdr = ["// GENERATED by tools/generate_hud_icons_c.py from assets/sprites/hud/*.png. Do not edit.",
           "// BGR555, BIT(15) = opaque, 0 = transparent.",
           "#ifndef HUD_ICONS_GFX_H", "#define HUD_ICONS_GFX_H", "", "#include <stdint.h>", "",
           f"#define HUD_ICON_W {w}", f"#define HUD_ICON_H {h}", ""]
    for name, *_ in data:
        hdr.append(f"extern const uint16_t {name}[HUD_ICON_W * HUD_ICON_H];")
    hdr += ["", "#endif", ""]
    write(ROOT / "include" / "hud_icons_gfx.h", "\n".join(hdr))
    print("wrote hud_icons_gfx.c/.h", w, h)


if __name__ == "__main__":
    main()
