#!/usr/bin/env python3
"""Bake the room fixtures (chest closed, chest open, travel altar) into include/enc_room_gfx.h.

The chests and the altar change state at run time, so they cannot be baked tiles in the cathedral kit
(tools/bake_cathedral_kit.py bakes only the door). source/encounters_act1.c paints them as software
sprites over the tilemap; this script turns the same renders into their pixel arrays.

Art: assets/environment/cathedral/props/render/<piece>/{color,shadow}.png, quantised to the shared
prop palette (assets/environment/cathedral/palette/palette.json) so the sprites use exactly the same
15-bit colours as the baked floor and props.

Usage: python tools/props/gen_room_sprites.py
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PROP_DIR = ROOT / "assets/environment/cathedral/props/render"
PALETTE = ROOT / "assets/environment/cathedral/palette/palette.json"
OUTPUT = ROOT / "include/enc_room_gfx.h"
# Identifier, render folder, and the sprite the runtime asks for.
SPRITES = (("cofre_cerrado", "cofre_cerrado"), ("cofre_abierto", "cofre_abierto"), ("altar", "altar"))


def rgb555(v):
    return np.array([(v & 31) * 255 // 31, ((v >> 5) & 31) * 255 // 31, ((v >> 10) & 31) * 255 // 31],
                    dtype=np.float64)


def prop_palette():
    colors = [int(c, 16) | 0x8000 for c in json.loads(PALETTE.read_text(encoding="utf-8"))["bgr555_hex"]["props"]]
    rgbs = np.stack([rgb555(c) for c in colors])
    return colors, rgbs


def load(name, colors, pal_rgb):
    d = PROP_DIR / name
    meta = json.loads((d / "meta.json").read_text(encoding="utf-8"))
    art = np.asarray(Image.open(d / "color.png").convert("RGBA"))
    sw, sh = meta["shadow_canvas_px"]
    dx, dy = meta["shadow_offset_px"]
    ox, oy = -dx, -dy
    full = np.zeros((sh, sw, 4), np.uint8)
    full[oy:oy + art.shape[0], ox:ox + art.shape[1]] = art
    opaque = full[:, :, 3] >= 128
    rgb = full[:, :, :3].astype(np.float64)
    flat = rgb.reshape(-1, 3)
    idx = np.empty(len(flat), np.int32)
    for i in range(0, len(flat), 4096):
        block = flat[i:i + 4096]
        d2 = ((block[:, None] - pal_rgb[None]) ** 2).sum(axis=2)
        idx[i:i + len(block)] = np.argmin(d2, axis=1)
    idx = idx.reshape(sh, sw)
    px = np.zeros((sh, sw), np.uint16)
    for y in range(sh):
        for x in range(sw):
            if opaque[y, x]:
                px[y, x] = colors[int(idx[y, x])]
    # Ground anchor: the lowest solid footprint cell, in colour-space pixels, moved into the canvas.
    foot = np.asarray(Image.open(d / "footprint.png").convert("L"))
    cells = (foot.reshape(foot.shape[0] // 4, 4, foot.shape[1] // 4, 4) >= 128).mean(axis=(1, 3)) > .40
    rows = [cy for cy in range(cells.shape[0]) if cells[cy].any()]
    if not rows:
        raise ValueError(f"{name}: footprint has no solid cell")
    anchor = max(rows) * 4 + 4 + oy
    return {"name": name, "w": sw, "h": sh, "anchor": anchor, "px": px}


def emit(specs):
    out = ["// Generated by tools/props/gen_room_sprites.py from assets/environment/cathedral/props/render.\n",
           "// Room fixtures painted by source/encounters_act1.c (chests and the travel altar).\n",
           "// Colours are BGR555 with bit 15 set; 0 is transparent. Do not edit.\n",
           "#ifndef ENC_ROOM_GFX_H\n#define ENC_ROOM_GFX_H\n\n#include <stdint.h>\n\n",
           "// One fixture sprite: `anchor_y` is the local Y of its ground point, so it is drawn at\n",
           "// (world_y - anchor_y) and its feet sit on the hero's line.\n",
           "typedef struct {\n    uint16_t w, h;\n    uint16_t anchor_y;\n",
           "    const uint16_t *pixels;\n} EncRoomSprite;\n\n"]
    for s in specs:
        flat = s["px"].reshape(-1)
        out.append(f"static const uint16_t s_room_{s['name']}_px[{len(flat)}] = {{\n")
        for i in range(0, len(flat), 16):
            out.append("    " + ", ".join(f"0x{v:04x}" for v in flat[i:i + 16]) + ",\n")
        out.append("};\n")
    out.append("static const EncRoomSprite s_enc_room_sprites[] = {\n")
    for s in specs:
        out.append(f"    {{ {s['w']}, {s['h']}, {s['anchor']}, s_room_{s['name']}_px }},"
                   f" // {s['name']}\n")
    out.append("};\n\nenum { ENC_SPR_COFRE_CERRADO = 0, ENC_SPR_COFRE_ABIERTO = 1, ENC_SPR_ALTAR = 2 };\n\n")
    out.append("#endif // ENC_ROOM_GFX_H\n")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: " + ", ".join(f"{s['name']} {s['w']}x{s['h']} anchor"
                                                          f" {s['anchor']}" for s in specs))


def main():
    colors, pal_rgb = prop_palette()
    specs = [load(folder, colors, pal_rgb) for _ident, folder in SPRITES]
    emit(specs)


if __name__ == "__main__":
    main()
