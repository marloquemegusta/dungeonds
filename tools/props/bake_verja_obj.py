#!/usr/bin/env python3
"""Genera el sprite 4bpp del rastrillo (verja) para sprites hardware OBJ.

usage: python tools/props/bake_verja_obj.py

Entrada:  assets/environment/cathedral/props/render/verja/color.png  (104x56 RGBA)
Salida:   include/verja_gfx.h  y  source/verja_gfx.c

Los pixeles opacos (alpha >= 128) se cuantizan a 15 colores con median cut (mas el indice 0
transparente). La paleta va en RGB15 (RGB15(r>>3, g>>3, b>>3)), indice 0 = 0. Los pixeles se
guardan como indices 0..15 (0 = transparente).
"""
import os

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "assets/environment/cathedral/props/render/verja/color.png")
HDR = os.path.join(ROOT, "include/verja_gfx.h")
SRC_C = os.path.join(ROOT, "source/verja_gfx.c")

W, H = 104, 56
PAL_N = 15            # opaque colours + index 0 transparent
ALPHA_MIN = 128


def median_cut(pixels, n):
    """Median cut sobre (r, g, b) enteros. Devuelve hasta n medias (arrays de 3 floats)."""
    boxes = [pixels]
    while len(boxes) < n:
        best, best_score = -1, 0
        for i, box in enumerate(boxes):
            if len(box) < 2:
                continue
            score = int((box.max(0) - box.min(0)).max()) * len(box)
            if score > best_score:
                best_score, best = score, i
        if best < 0:
            break
        box = boxes.pop(best)
        ch = int((box.max(0) - box.min(0)).argmax())
        box = box[np.argsort(box[:, ch], kind="stable")]
        mid = len(box) // 2
        boxes.append(box[:mid])
        boxes.append(box[mid:])
    return [box.mean(0) for box in boxes]


def rgb15(c):
    r, g, b = (int(round(v)) for v in c)
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def main():
    im = Image.open(SRC).convert("RGBA")
    if im.size != (W, H):
        raise ValueError(f"{SRC}: expected {W}x{H}, got {im.size}")
    a = np.asarray(im)
    rgb = a[:, :, :3].astype(np.int32)
    opaque = a[:, :, 3] >= ALPHA_MIN

    px = rgb[opaque]
    means = median_cut(px, PAL_N)
    if len(means) < PAL_N:                      # fewer unique colours than the palette: pad with black
        means += [np.zeros(3)] * (PAL_N - len(means))
    pal = np.array(means, dtype=np.float64)     # (PAL_N, 3)

    palette = [0] * 16
    for i in range(PAL_N):
        palette[i + 1] = rgb15(pal[i])

    pixels = np.zeros((H, W), dtype=np.uint8)
    if len(px):
        d = ((px[:, None, :] - pal[None, :, :]) ** 2).sum(2)    # (N, PAL_N)
        idx = d.argmin(1) + 1                                  # 1..15
        pixels[opaque] = idx.astype(np.uint8)

    header = """// GENERATED by tools/props/bake_verja_obj.py from
// assets/environment/cathedral/props/render/verja/color.png. Do not edit.
// Hardware OBJ sprite: 15-colour 4bpp art (index 0 transparent).
#ifndef VERJA_GFX_H
#define VERJA_GFX_H

#include <stdint.h>

#define VERJA_W 104
#define VERJA_H 56

extern const uint16_t g_verja_palette[16];
extern const uint8_t g_verja_pixels[VERJA_H][VERJA_W];

#endif
"""
    with open(HDR, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)

    lines = ["// GENERATED by tools/props/bake_verja_obj.py from "
             "assets/environment/cathedral/props/render/verja/color.png. Do not edit.",
             '#include "verja_gfx.h"',
             "",
             "// RGB15 (RGB15(r>>3, g>>3, b>>3)); index 0 = transparent.",
             "const uint16_t g_verja_palette[16] = {"]
    for i in range(0, 16, 8):
        lines.append("    " + ", ".join("0x%04X" % v for v in palette[i:i + 8]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("// 4bpp colour indices 0..15 (0 = transparent).")
    lines.append("const uint8_t g_verja_pixels[VERJA_H][VERJA_W] = {")
    for y in range(H):
        lines.append("    {" + ", ".join("%2d" % v for v in pixels[y]) + "},")
    lines.append("};")
    with open(SRC_C, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    print(f"verja: {W}x{H}, opaque {int(opaque.sum())} px, palette {len(set(map(tuple, pal.tolist())))} "
          f"distinct colours -> {HDR} / {SRC_C}")


if __name__ == "__main__":
    main()
