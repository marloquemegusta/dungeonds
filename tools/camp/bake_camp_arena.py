#!/usr/bin/env python3
"""Bakes the camp floor + walls into a small static arena data file.

The camp reuses the cathedral floor tiles and the cathedral wall art (no new tiles), but the
floor palette is recoloured (paler, colder, slightly greenish: stone in the open air). Walls keep
the cathedral colours, so the shared palette concatenates the recoloured floor colours and the
original wall colours.

Output: include/camp_arena_data.h and source/camp_arena_data.c. The runtime Arena (with its
collision grid and the props) is built in source/camp.c; this file only owns the art data.
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import bake_cathedral_kit as kit  # noqa: E402

FLOOR_DIR = ROOT / "assets/environment/cathedral/floor/rombos_tripo"
WALL_PNG = ROOT / "assets/environment/cathedral/muros/muro_izq_128.png"

CAMP_W_PX = 256
CAMP_H_PX = 384
TILES_W = CAMP_W_PX // 8   # 32
TILES_H = CAMP_H_PX // 8   # 48
WALL_INNER_COLS = 3        # 24 px of wall on each side of the 256 view (as the encounters composer)
WALL_TILE_COLS = 6


def clamp5(v):
    return 0 if v < 0 else 31 if v > 31 else v


def recolor_floor(c):
    """Paler, colder, a touch green: shift towards light weathered stone without changing hue much."""
    r = c & 31
    g = (c >> 5) & 31
    b = (c >> 10) & 31
    r = clamp5(r + (31 - r) // 10 - 1)
    g = clamp5(g + (31 - g) // 6)
    b = clamp5(b + (31 - b) // 4)
    return r | (g << 5) | (b << 10) | 0x8000


def main():
    tiles = kit.Tiles()
    floor_colors, floor_raw, floor_grid = kit.read_floor(FLOOR_DIR)
    palette, _pixel_tiles, floor_map64 = kit.make_floor_tiles(floor_colors, floor_raw, floor_grid, tiles)

    # Recolour the floor colours (index 0 is the transparent/void entry and stays 0).
    palette = [palette[0]] + [recolor_floor(c) for c in palette[1:]]

    # Walls: quantise the cathedral wall PNG to the prop palette, keep the cathedral colours.
    prop_colors, prop_lab = kit.read_prop_palette()
    src = np.asarray(Image.open(WALL_PNG).convert("RGBA"))
    if src.shape != (128, WALL_TILE_COLS * 8, 4):
        raise ValueError(f"wall must be {WALL_TILE_COLS*8}x128, got {src.shape[1]}x{src.shape[0]}")
    opaque = src[:, :, 3] >= 128
    rgb = np.where(opaque[:, :, None], src[:, :, :3], np.array(kit.WALL_BACKDROP_RGB, np.uint8))
    comp = np.dstack([rgb, np.full(opaque.shape, 255, np.uint8)])
    q = kit.quantize_props(Image.fromarray(comp), prop_lab)
    table = {}
    for i in np.unique(q):
        color = prop_colors[int(i)]
        if color not in palette:
            palette.append(color)
        table[int(i)] = palette.index(color)
    wall_idx = np.vectorize(lambda v: table[int(v)])(q).astype(np.uint8)

    def add_tile(bytes_):
        return tiles.add(bytes_)

    # Left wall: the inner 3 tile columns of each 16-row wall slice.
    wall_left = [[0] * WALL_INNER_COLS for _ in range(16)]
    for ty in range(16):
        for c in range(WALL_INNER_COLS):
            tx = WALL_TILE_COLS - WALL_INNER_COLS + c   # columns 3,4,5 (inner edge)
            block = np.ascontiguousarray(wall_idx[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8])
            wall_left[ty][c] = add_tile(block.tobytes())

    # Full 48-row × 32-col map: floor in the middle, 3 columns of wall each side.
    camp_map = []
    for r in range(TILES_H):
        row = list(floor_map64[r % 16][:TILES_W])
        for c in range(WALL_INNER_COLS):
            entry = wall_left[r % 16][c]
            row[c] = entry                    # left wall
            row[TILES_W - 1 - c] = entry ^ 0x4000   # right wall: mirrored
        camp_map.append(row)

    if len(palette) > 256:
        raise ValueError(f"camp palette needs {len(palette)} entries (>256)")

    hdr = [
        "// GENERATED by tools/camp/bake_camp_arena.py. Do not edit.",
        "#ifndef CAMP_ARENA_DATA_H",
        "#define CAMP_ARENA_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define CAMP_WORLD_W {CAMP_W_PX}",
        f"#define CAMP_WORLD_H {CAMP_H_PX}",
        f"#define CAMP_MAP_W {TILES_W}",
        f"#define CAMP_MAP_H {TILES_H}",
        f"#define CAMP_NUM_TILES {len(tiles.data)}",
        "",
        "extern const uint16_t g_camp_palette[256];",
        "extern const uint8_t g_camp_tiles[CAMP_NUM_TILES][64];",
        "extern const uint16_t g_camp_floor_map[CAMP_MAP_W * CAMP_MAP_H];",
        "",
        "#endif",
        "",
    ]
    (ROOT / "include" / "camp_arena_data.h").write_text("\n".join(hdr), encoding="utf-8", newline="")

    c = [
        "// GENERATED by tools/camp/bake_camp_arena.py. Do not edit.",
        '#include "camp_arena_data.h"',
        "",
        "const uint16_t g_camp_palette[256] __attribute__((aligned(4))) = {",
    ]
    pad = palette + [0] * (256 - len(palette))
    for i in range(0, 256, 16):
        c.append("    " + ", ".join(f"0x{v:04X}" for v in pad[i:i + 16]) + ",")
    c += ["};", "", "const uint8_t g_camp_tiles[CAMP_NUM_TILES][64] __attribute__((aligned(4))) = {"]
    for t in tiles.data:
        c.append("    { " + ", ".join(map(str, t)) + " },")
    c += ["};", "", "const uint16_t g_camp_floor_map[CAMP_MAP_W * CAMP_MAP_H] __attribute__((aligned(4))) = {"]
    for row in camp_map:
        c.append("    " + ", ".join(map(str, row)) + ",")
    c += ["};", ""]
    (ROOT / "source" / "camp_arena_data.c").write_text("\n".join(c), encoding="utf-8", newline="")
    print(f"camp arena: {len(tiles.data)} tiles, {len(palette)} colours, {TILES_W}x{TILES_H} map")


if __name__ == "__main__":
    main()
