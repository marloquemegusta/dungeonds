#!/usr/bin/env python3
"""Bakes the camp props (prerendered colour PNGs) into RGB15 C data.

The camp is drawn as software sprites over the recoloured cathedral floor (see source/camp.c).
Reads assets/environment/cathedral/props/render/<piece>/color.png and shadow.png, the same art the
cathedral kit uses, and writes:
  include/camp_props_gfx.h
  source/camp_props_gfx.c
Night camp (DESIGN.md 7.5): the pieces are the camp_n_* variants (render/camp_n_<piece>/, lit by the bonfire,
made by tools/props/props_camp_night.py). Pixels are converted straight to RGB15 (no quantisation to the
cathedral prop palette: the camp is software-blitted RGB15 and the fire-lit tones would band).
It also writes the animated bonfire flame strip (tools/camp/fuego_frames.py -> nitrofiles/camp/hoguera_fuego.bin).
Pixels keep BIT(15) (opaque) so the blit copies them straight to the 16 bpp page; transparent is 0.
Each piece also exports its baked ground-shadow mask (shadow.png on the shadow canvas declared by
meta.json), packed as 4-bit nibbles like the actor shadows, so source/camp.c can darken the floor
with draw_shadow_mask exactly like the actors do.
"""
import sys
from pathlib import Path

from PIL import Image
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

RENDER = ROOT / "assets" / "environment" / "cathedral" / "props" / "render"

# symbol suffix -> source piece directory
PIECES = [
    ("hoguera", "camp_n_hoguera"),
    ("jergon",  "camp_n_jergon"),
    ("atril",   "camp_n_atril"),
    ("mesa",    "camp_n_mesa"),
    ("arcon",   "camp_n_arcon"),
    ("puerta",  "camp_n_puerta"),
]


def img_to_words(path):
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im).astype(np.int32)
    words = ((a[:, :, 0] >> 3) | ((a[:, :, 1] >> 3) << 5) | ((a[:, :, 2] >> 3) << 10) | 0x8000)
    words = np.where(a[:, :, 3] < 128, 0, words)
    return im.width, im.height, words.reshape(-1).tolist()


def load_shadow(piece_dir, w, h):
    """Ground-shadow mask on the canvas declared by meta.json, minus the piece's own pixels.
    Returns (mask bytes packed 4-bit per pixel, canvas w, canvas h, ox, oy) or None."""
    shadow_path = piece_dir / "shadow.png"
    if not shadow_path.exists():
        return None
    import json
    meta = json.loads((piece_dir / "meta.json").read_text(encoding="utf-8"))
    dx, dy = meta["shadow_offset_px"]
    sw, sh = meta["shadow_canvas_px"]
    ox, oy = -dx, -dy
    shadow = np.asarray(Image.open(shadow_path).convert("L")) > 127
    rgba = np.asarray(Image.open(piece_dir / "color.png").convert("RGBA"))
    full_alpha = np.zeros((sh, sw), np.uint8)
    full_alpha[oy:oy + h, ox:ox + w] = rgba[:, :, 3]
    shadow = shadow & (full_alpha < 128)
    # 4-bit nibbles, low nibble = even x (same packing as draw_shadow_mask in source/main.c).
    packed = bytearray()
    for y in range(sh):
        for x in range(0, sw, 2):
            lo = 0x0F if shadow[y, x] else 0
            hi = 0x0F if (x + 1 < sw and shadow[y, x + 1]) else 0
            packed.append(lo | (hi << 4))
    # Canvas top-left relative to the colour sprite top-left (negative: the canvas reaches left).
    return bytes(packed), sw, sh, -ox, -oy


def write_lf(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def main():
    parsed = []
    for suffix, piece in PIECES:
        piece_dir = RENDER / piece
        w, h, px = img_to_words(piece_dir / "color.png")
        shadow = load_shadow(piece_dir, w, h)
        parsed.append((suffix, piece, w, h, px, shadow))

    # Pixels and shadows go to NitroFS (nitro:/camp/<stem>.bin), not into the ARM9 binary: the static
    # EWRAM budget is full (TECHNICAL.md §3.3). source/camp.c reads them once when the room is built.
    out_dir = ROOT / "nitrofiles" / "camp"
    out_dir.mkdir(parents=True, exist_ok=True)
    hdr = [
        "// GENERATED by tools/camp/generate_camp_gfx.py. Do not edit.",
        "// Pixel and shadow data: nitrofiles/camp/<stem>.bin and <stem>_shadow.bin (loaded by source/camp.c).",
        "#ifndef CAMP_PROPS_GFX_H",
        "#define CAMP_PROPS_GFX_H",
        "",
    ]
    for suffix, piece, w, h, px, shadow in parsed:
        tag = suffix.upper()
        hdr.append(f"#define CAMP_{tag}_W {w}")
        hdr.append(f"#define CAMP_{tag}_H {h}")
        raw = b"".join(int(v).to_bytes(2, "little") for v in px)
        (out_dir / f"{suffix}.bin").write_bytes(raw)
        if shadow is not None:
            packed, sw, sh, ox, oy = shadow
            hdr.append(f"#define CAMP_{tag}_SHADOW_W {sw}")
            hdr.append(f"#define CAMP_{tag}_SHADOW_H {sh}")
            hdr.append(f"#define CAMP_{tag}_SHADOW_OX {ox}")
            hdr.append(f"#define CAMP_{tag}_SHADOW_OY {oy}")
            (out_dir / f"{suffix}_shadow.bin").write_bytes(packed)
    # Bonfire flame: FRAMES frames of W x H RGB15 stacked vertically; root = bottom-centre (BASE_X, H-1).
    import fuego_frames
    (out_dir / "hoguera_fuego.bin").write_bytes(fuego_frames.strip_bytes())
    hdr += ["", f"#define CAMP_FUEGO_W {fuego_frames.W}", f"#define CAMP_FUEGO_H {fuego_frames.H}",
            f"#define CAMP_FUEGO_FRAMES {fuego_frames.FRAMES}", f"#define CAMP_FUEGO_BASE_X {fuego_frames.BASE_X}"]
    hdr += ["", "#endif", ""]
    write_lf(ROOT / "include" / "camp_props_gfx.h", "\n".join(hdr))
    stale = ROOT / "source" / "camp_props_gfx.c"
    if stale.exists():
        stale.unlink()
    print("Wrote nitrofiles/camp/*.bin and include/camp_props_gfx.h")


if __name__ == "__main__":
    main()
