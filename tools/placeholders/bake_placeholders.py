#!/usr/bin/env python3
"""Bakes the placeholder lab renders into 12x12 sprites (8x8 for aliado_marca) and writes the C data.

  python tools/placeholders/bake_placeholders.py

  assets/sprites/placeholders/source/<name>.png  ->  assets/sprites/placeholders/<name>.png
                                                 ->  include/placeholders_gfx.h + source/placeholders_gfx.c

Same C2 post-process as tools/hud/bake_hud_heart.py: premultiplied LANCZOS resize, BOX alpha with
threshold 0.30, soft_contrast(1.45), alpha-aware sharpen(0.5). The content is cropped to its alpha
box, scaled to fit the sprite, and placed bottom-centre (ground contact on the bottom row).
Pixels are RGB15 with BIT(15) = opaque, 0 = transparent (same as the HUD icons).
"""
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets" / "sprites" / "placeholders" / "source"
OUT = ROOT / "assets" / "sprites" / "placeholders"
INC = ROOT / "include" / "placeholders_gfx.h"
SRC_C = ROOT / "source" / "placeholders_gfx.c"
ALPHA_THRESH = 0.30

# name: (canvas size W, H)
SPRITES = {
    "runa_xp": 12,
    "orbe_vida": 12,
    "orbe_mana": 12,
    "maldicion": 12,
    "aliado_marca": 8,
}


def soft_contrast(rgb, gain=1.45):
    f = rgb / 255.0
    L = 0.2126 * f[..., 0] + 0.7152 * f[..., 1] + 0.0722 * f[..., 2]
    p = float(np.median(L))
    d = L - p
    m = np.where(d < 0, p, 1 - p)
    out = p + d * gain / (1 + (gain - 1) * np.abs(d) / np.maximum(m, 1e-4))
    scale = np.where(L > 1e-4, out / np.maximum(L, 1e-4), 1)
    return np.clip(f * scale[..., None], 0, 1) * 255.0


def blur3(x):
    k = np.array([1.0, 2.0, 1.0]) / 4.0
    p = np.pad(x, ((1, 1), (1, 1)) + ((0, 0),) * (x.ndim - 2), mode="edge")
    h = k[0] * p[:, :-2] + k[1] * p[:, 1:-1] + k[2] * p[:, 2:]
    return k[0] * h[:-2] + k[1] * h[1:-1] + k[2] * h[2:]


def sharpen_rgba(rgba, amount=0.5):
    rgb = rgba[..., :3].astype(float)
    m = (rgba[..., 3] > 0).astype(float)
    bl = blur3(rgb * m[..., None]) / np.maximum(blur3(m), 1e-3)[..., None]
    out = rgba.copy()
    out[..., :3] = np.clip(rgb + amount * (rgb - bl), 0, 255).astype(np.uint8)
    return out


def bake(src_png, box, canvas):
    """Returns an RGBA array of shape (canvas, canvas, 4)."""
    src = Image.open(src_png).convert("RGBA")
    src = src.crop(src.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox())
    scale = min(box / src.width, box / src.height)
    cw, ch = max(1, round(src.width * scale)), max(1, round(src.height * scale))

    arr = np.array(src)
    rgb_src = arr[..., :3].astype(np.float32)
    m_src = (arr[..., 3] > 127).astype(np.float32)
    chans = []
    for c in range(3):
        im = Image.fromarray(rgb_src[..., c] * m_src, mode="F").resize((cw, ch), Image.LANCZOS)
        chans.append(np.array(im))
    am = np.array(Image.fromarray(m_src, mode="F").resize((cw, ch), Image.BOX))
    a = am >= ALPHA_THRESH
    rgb = np.clip(np.stack(chans, -1) / np.maximum(am[..., None], 1e-3), 0, 255).astype(np.uint8)

    content = np.zeros((ch, cw, 4), np.uint8)
    content[..., :3] = rgb * a[..., None]
    content[..., 3] = a * 255
    if a.any():
        content[..., :3][a] = soft_contrast(content[..., :3][a].astype(float)[None], 1.45)[0].astype(np.uint8)
        content = sharpen_rgba(content, 0.5)

    out = np.zeros((canvas, canvas, 4), np.uint8)
    x0 = (canvas - cw) // 2
    y0 = canvas - ch
    out[y0:y0 + ch, x0:x0 + cw] = content
    return out


def words(rgba):
    h, w = rgba.shape[:2]
    out = []
    for y in range(h):
        for x in range(w):
            r, g, b, al = (int(v) for v in rgba[y, x])
            if al < 128:
                out.append(0)
            else:
                r5 = min(31, (r * 31 + 127) // 255)
                g5 = min(31, (g * 31 + 127) // 255)
                b5 = min(31, (b * 31 + 127) // 255)
                out.append(0x8000 | r5 | (g5 << 5) | (b5 << 10))
    return out


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:  # keep LF on Windows
        f.write(text)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    c = ["// GENERATED by tools/placeholders/bake_placeholders.py from assets/sprites/placeholders/*.png. Do not edit.",
         '#include "placeholders_gfx.h"', ""]
    h = ["// GENERATED by tools/placeholders/bake_placeholders.py from assets/sprites/placeholders/*.png. Do not edit.",
         "// RGB15 (BGR555), BIT(15) = opaque, 0 = transparent. Temporary placeholders.",
         "#ifndef PLACEHOLDERS_GFX_H", "#define PLACEHOLDERS_GFX_H", "", "#include <stdint.h>", ""]
    for name, size in SPRITES.items():
        rgba = bake(SRC / (name + ".png"), size, size)
        Image.fromarray(rgba, "RGBA").save(OUT / (name + ".png"))
        px = words(rgba)
        up = name.upper()
        h.append(f"#define PH_{up}_W {size}")
        h.append(f"#define PH_{up}_H {size}")
        c.append(f"// {name}.png")
        c.append(f"const uint16_t g_ph_{name}[PH_{up}_W * PH_{up}_H] = {{")
        for y in range(size):
            c.append("    " + ", ".join(f"0x{v:04X}" for v in px[y * size:(y + 1) * size]) + ",")
        c.append("};")
        c.append("")
        opaque = int(rgba[..., 3].astype(bool).sum())
        print(f"baked {name} {size}x{size} opaque px={opaque}")
    h.append("")
    for name in SPRITES:
        h.append(f"extern const uint16_t g_ph_{name}[PH_{name.upper()}_W * PH_{name.upper()}_H];")
    h += ["", "#endif", ""]
    write(SRC_C, "\n".join(c))
    write(INC, "\n".join(h))
    print("wrote", INC, "and", SRC_C)


if __name__ == "__main__":
    main()
