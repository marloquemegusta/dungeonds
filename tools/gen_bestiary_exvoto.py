#!/usr/bin/env python3
"""
tools/gen_bestiary_exvoto.py - Extracts and encodes El Exvoto walk strip for Bestiary.

Reads:
  c:/codexlocal/dungeonds/.worktrees/exvoto-anim/walkthroughs/exvoto-anim/assets/lab_walk/spritesheet.png
  (Row 0: 8 frames of 40x40 front walk in-place)

Generates:
  include/bestiary_exvoto.h
  source/bestiary_exvoto.c
  walkthroughs/bestiario/assets/exvoto_preview.gif (visual verification)
"""

import os
import sys
import argparse
from PIL import Image

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
WT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, '..'))

DEFAULT_SRC = r'c:\codexlocal\dungeonds\.worktrees\exvoto-anim\walkthroughs\exvoto-anim\assets\lab_walk\spritesheet.png'
ALPHA_THRESH = 77  # Mode c2 threshold

def extract_exvoto_strip(src_path):
    if not os.path.exists(src_path):
        raise FileNotFoundError(f'Source spritesheet not found: {src_path}')

    im = Image.open(src_path).convert('RGBA')
    frame_w, frame_h = 40, 40
    num_frames = 8

    bounds = []
    offsets = []
    all_pixels = []
    preview_frames = []

    for f in range(num_frames):
        cell = im.crop((f * frame_w, 0, (f + 1) * frame_w, frame_h))
        preview_frames.append(cell)

        # 1. Bounding box computation (alpha >= 77)
        min_x, max_x = frame_w, -1
        min_y, max_y = frame_h, -1
        buf = [0] * (frame_w * frame_h)

        for y in range(frame_h):
            for x in range(frame_w):
                r, g, b, a = cell.getpixel((x, y))
                if a < ALPHA_THRESH:
                    val = 0
                else:
                    # c2 rounded 5-bit conversion with bit 15 set for opaque
                    r5 = (r * 31 + 127) // 255
                    g5 = (g * 31 + 127) // 255
                    b5 = (b * 31 + 127) // 255
                    val = r5 | (g5 << 5) | (b5 << 10) | 0x8000
                    if x < min_x: min_x = x
                    if x > max_x: max_x = x
                    if y < min_y: min_y = y
                    if y > max_y: max_y = y
                buf[y * frame_w + x] = val

        if max_x < min_x:
            bounds.append((0, 0, 0, 0))
            offsets.append(len(all_pixels))
        else:
            bw = max_x - min_x + 1
            bh = max_y - min_y + 1
            bounds.append((min_x, min_y, bw, bh))
            offsets.append(len(all_pixels))

            for y in range(min_y, max_y + 1):
                row_slice = buf[y * frame_w + min_x : y * frame_w + max_x + 1]
                all_pixels.extend(row_slice)
                if bw & 1:
                    all_pixels.append(0)  # even row pitch (32-bit aligned rows)

    return bounds, offsets, all_pixels, preview_frames

def generate_header(out_h_path):
    content = """/* Automatically generated by tools/gen_bestiary_exvoto.py - DO NOT EDIT */
#ifndef BESTIARY_EXVOTO_H
#define BESTIARY_EXVOTO_H

#include <stdint.h>

#define BESTIARY_EXVOTO_NUM_FRAMES 8
#define BESTIARY_EXVOTO_FRAME_W    40
#define BESTIARY_EXVOTO_FRAME_H    40

static inline int bestiary_exvoto_pitch(int bw) {
    return (bw + 1) & ~1;
}

extern const uint8_t  bestiary_exvoto_bounds[BESTIARY_EXVOTO_NUM_FRAMES][4];
extern const uint32_t bestiary_exvoto_offsets[BESTIARY_EXVOTO_NUM_FRAMES];
extern const uint16_t bestiary_exvoto_frames[];

/* Convenient aliases matching engine conventions */
#define g_bestiary_exvoto_bounds  bestiary_exvoto_bounds
#define g_bestiary_exvoto_offsets bestiary_exvoto_offsets
#define g_bestiary_exvoto_frames  bestiary_exvoto_frames

/* Helper to draw an Exvoto frame into a 256x192 16bpp framebuffer (clipped).
 * scale: 1 for 1x native, 2 for 2x scale.
 */
void bestiary_exvoto_draw_frame(uint16_t *fb, int frame_idx, int dst_x, int dst_y, int scale);

#endif /* BESTIARY_EXVOTO_H */
"""
    os.makedirs(os.path.dirname(out_h_path), exist_ok=True)
    with open(out_h_path, 'w', encoding='utf-8') as f:
        f.write(content)

def generate_source(out_c_path, bounds, offsets, all_pixels):
    lines = []
    lines.append('/* Automatically generated by tools/gen_bestiary_exvoto.py - DO NOT EDIT */\n')
    lines.append('#include "bestiary_exvoto.h"\n\n')

    # Bounds
    lines.append('const uint8_t bestiary_exvoto_bounds[BESTIARY_EXVOTO_NUM_FRAMES][4] = {\n')
    for f, (x, y, w, h) in enumerate(bounds):
        lines.append(f'    {{ {x:2d}, {y:2d}, {w:2d}, {h:2d} }},  /* Frame {f} */\n')
    lines.append('};\n\n')

    # Offsets
    lines.append('const uint32_t bestiary_exvoto_offsets[BESTIARY_EXVOTO_NUM_FRAMES] = {\n')
    for f, off in enumerate(offsets):
        lines.append(f'    {off:5d},  /* Frame {f} */\n')
    lines.append('};\n\n')

    # Frames array
    lines.append(f'const uint16_t bestiary_exvoto_frames[{len(all_pixels)}] __attribute__((aligned(4))) = {{\n')
    for i in range(0, len(all_pixels), 8):
        chunk = all_pixels[i:i+8]
        hex_vals = ', '.join(f'0x{v:04X}' for v in chunk)
        lines.append(f'    {hex_vals},\n')
    lines.append('};\n\n')

    # Draw frame helper implementation
    lines.append("""void bestiary_exvoto_draw_frame(uint16_t *fb, int frame_idx, int dst_x, int dst_y, int scale) {
    if (!fb || frame_idx < 0 || frame_idx >= BESTIARY_EXVOTO_NUM_FRAMES) return;
    const uint8_t *b = bestiary_exvoto_bounds[frame_idx];
    int min_x = b[0], min_y = b[1], bw = b[2], bh = b[3];
    if (bw <= 0 || bh <= 0) return;
    int pitch = bestiary_exvoto_pitch(bw);
    const uint16_t *src = &bestiary_exvoto_frames[bestiary_exvoto_offsets[frame_idx]];

    if (scale <= 1) {
        for (int y = 0; y < bh; y++) {
            int py = dst_y + min_y + y;
            if (py < 0 || py >= 192) continue;
            uint16_t *row = fb + (py << 8);
            for (int x = 0; x < bw; x++) {
                uint16_t px = src[y * pitch + x];
                if (px & 0x8000) {
                    int pxx = dst_x + min_x + x;
                    if (pxx >= 0 && pxx < 256) {
                        row[pxx] = px;
                    }
                }
            }
        }
    } else {
        for (int y = 0; y < bh; y++) {
            int py0 = dst_y + (min_y + y) * 2;
            int py1 = py0 + 1;
            for (int x = 0; x < bw; x++) {
                uint16_t px = src[y * pitch + x];
                if (px & 0x8000) {
                    int px0 = dst_x + (min_x + x) * 2;
                    int px1 = px0 + 1;
                    if (py0 >= 0 && py0 < 192) {
                        uint16_t *row0 = fb + (py0 << 8);
                        if (px0 >= 0 && px0 < 256) row0[px0] = px;
                        if (px1 >= 0 && px1 < 256) row0[px1] = px;
                    }
                    if (py1 >= 0 && py1 < 192) {
                        uint16_t *row1 = fb + (py1 << 8);
                        if (px0 >= 0 && px0 < 256) row1[px0] = px;
                        if (px1 >= 0 && px1 < 256) row1[px1] = px;
                    }
                }
            }
        }
    }
}
""")

    os.makedirs(os.path.dirname(out_c_path), exist_ok=True)
    with open(out_c_path, 'w', encoding='utf-8') as f:
        f.writelines(lines)

def save_preview_gif(preview_frames, gif_path):
    scaled_frames = [f.resize((f.width * 4, f.height * 4), Image.NEAREST) for f in preview_frames]
    os.makedirs(os.path.dirname(gif_path), exist_ok=True)
    scaled_frames[0].save(
        gif_path,
        save_all=True,
        append_images=scaled_frames[1:],
        duration=60,
        loop=0,
        disposal=2
    )
    print(f'Preview GIF saved: {gif_path}')

def main():
    parser = argparse.ArgumentParser(description='Extract and encode El Exvoto front strip')
    parser.add_argument('--src', default=DEFAULT_SRC, help='Input spritesheet PNG')
    parser.add_argument('--out-h', default=os.path.join(WT_ROOT, 'include', 'bestiary_exvoto.h'))
    parser.add_argument('--out-c', default=os.path.join(WT_ROOT, 'source', 'bestiary_exvoto.c'))
    parser.add_argument('--out-gif', default=os.path.join(WT_ROOT, 'walkthroughs', 'bestiario', 'assets', 'exvoto_preview.gif'))
    args = parser.parse_args()

    print(f'Reading spritesheet: {args.src}...')
    bounds, offsets, all_pixels, preview_frames = extract_exvoto_strip(args.src)
    print(f'Extracted 8 frames, total {len(all_pixels)} uint16 words ({len(all_pixels)*2} bytes).')
    for f in range(8):
        bx, by, bw, bh = bounds[f]
        print(f'  Frame {f}: bounds=({bx}, {by}, {bw}, {bh}), offset={offsets[f]}')

    print(f'Writing {args.out_h}...')
    generate_header(args.out_h)

    print(f'Writing {args.out_c}...')
    generate_source(args.out_c, bounds, offsets, all_pixels)

    print(f'Generating preview GIF {args.out_gif}...')
    save_preview_gif(preview_frames, args.out_gif)

    print('El Exvoto bestiary strip generation complete.')

if __name__ == '__main__':
    main()
